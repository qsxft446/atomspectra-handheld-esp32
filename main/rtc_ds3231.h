#pragma once
// #RTC-1: часы реального времени DS3231 (I2C 0x68) на общей шине board_i2c.h
// (GPIO8/9, та же шина, что BQ25895 и тач FT6336U). Опциональный модуль: если
// на шине никто не отвечает — present=false, прошивка живёт как раньше
// (время только от SNTP/браузера).
//
// Роль: источник времени платы без сети. Хранит UTC.
//   - старт платы: если в DS3231 валидное время (флаг OSF сброшен) —
//     settimeofday() и источник TIME_SRC_RTC;
//   - любая внешняя установка (SNTP, браузер, ручная) — записать в DS3231;
//   - раз в час, пока нет SNTP, — подправить часы ESP32 по DS3231
//     (кварц ESP32 уходит на секунды в сутки, DS3231 — ±2 ppm).
#include <stdbool.h>

// Вызывать из app_main() ПОСЛЕ battery_init() (шина I2C) и ДО модулей, которые
// фиксируют время старта (spectrogram_init, usb_host_cdc_init).
void rtc_ds3231_init(void);

bool rtc_ds3231_present(void);     // модуль ответил на шине
bool rtc_ds3231_time_valid(void);  // в модуле валидное время (OSF сброшен)

// Записать текущее время платы в DS3231 (после SNTP/браузера/ручной установки).
// Безопасно вызывать без модуля — ничего не делает.
void rtc_ds3231_save_now(void);

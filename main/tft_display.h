#pragma once
// #TFT-1: ST7796U 480x320 (SPI, единственный ведущий SPI2_HOST — поддержка
// W5500 из проекта вырезана, шину поднимает сам этот модуль)
// + ёмкостный тач FT6336U (I2C, делит шину с board_i2c.h — battery.c/BQ25895).
// Экран «Спектр» (#TFT-18) — мини-копия страницы спектра web/index.html:
// шапка (CPS, время, всего, доза), log10 CPS с полом в один отсчёт, ось кэВ по
// калибровке, палитра веба. Окно каналов — ползунок на вкладке Conf (#TFT-29). Экран «Монитор» — общая с вебом
// сессия мониторинга платы (#MON-2, monitor.h). Экран «Водопад» — строки
// кольца spectrogram.c, как страница водопада веба (#TFT-28).
//
// Полностью заменяет прежний SSD1306 (oled_display.c удалён).

// Инициализирует SPI-шину и панель, тач-контроллер, LVGL и запускает фоновую
// задачу рендера. Вызывать один раз из app_main(), ПОСЛЕ battery_init()
// (нужна уже поднятая общая I2C-шина board_i2c.h).
void tft_display_init(void);

#include <stdbool.h>

// #TFT-21: калибровка тача (для страницы «Система» веба).
bool tft_display_present(void);            // экран поднят полностью
bool tft_display_touch_calibrated(void);   // в NVS есть калибровка тача
// Запустить процедуру на экране (крестики по очереди). Только ставит команду в
// очередь задачи экрана — безопасно из любой задачи. false — нет экрана/тача.
bool tft_display_start_touch_cal(void);

// #SD-2: развязка общей шины SPI с SD-картой модуля (sd_card.c). Кадр экрана
// уходит по SPI целиком, пока задача LVGL держит свой замок, поэтому любая
// команда карты берёт тот же замок. Без экрана — ничего не делают.
void tft_display_spi_lock(void);
void tft_display_spi_unlock(void);
